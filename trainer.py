"""
trainer.py

Small supervised-training helpers shared by the MLP and the from-scratch transformer scripts.
"""
import random

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

from common import PASTA, epoch_pairs, steps_per_epoch

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)



def fit_supervised(model, encode, train, *, epochs, lr, bs=32,
                   wd=0.05, ls=0.1, drop=0.1, seed=0, log=print):
    """Train a classification model using supervised learning.

    Trains the model to predict the correct class (surname or pasta)
    using cross-entropy loss. Each epoch uses class-balanced training
    data with random character deletion for data augmentation.

    Model parameters are updated through backpropagation using the
    AdamW optimizer, with a OneCycle learning rate schedule,
    label smoothing, and gradient clipping to improve training
    stability and generalization.

    Args:
        model (nn.Module): Neural network to train. Must output
            two classification logits for each input word.
        encode (callable): Function that converts a list of words
            into input tensors compatible with the model.
        train (list[tuple[str, int]]): Training words paired with
            their labels (0 = surname, 1 = pasta).
        epochs (int): Number of complete training epochs.
        lr (float): Maximum learning rate used by OneCycleLR.
        bs (int): Mini-batch size. Defaults to 32.
        wd (float): Weight decay for AdamW regularization.
            Defaults to 0.05.
        ls (float): Label smoothing factor for cross-entropy loss.
            Defaults to 0.1.
        drop (float): Probability of randomly deleting each
            character during data augmentation. Defaults to 0.1.
        seed (int): Random seed for sampling and augmentation.
            Defaults to 0.
        log (callable): Function used to report training progress.
            Defaults to print.

    Returns:
        None: The model is updated in place during training.

    Notes:
        - Each epoch contains an equal number of examples from
          both classes, generated by common.epoch_pairs().
        - Gradient norms are clipped to a maximum of 1.0.
        - The learning rate is adjusted after every mini-batch.
        - Training loss and accuracy are periodically logged.
        - No validation or early stopping is performed.
    """
    rng = random.Random(seed)

    # Initialize AdamW optimizer and OneCycle learning rate scheduler.
    opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=wd)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=lr, total_steps=epochs * steps_per_epoch(train, bs))

    for ep in range(epochs):
        # Enable training mode (activates dropout layers).
        model.train()
        loss_sum = correct = n = 0

        # Generate a shuffled, class-balanced epoch with character deletion.
        pairs = epoch_pairs(train, rng, drop)

        for i in range(0, len(pairs), bs):
            chunk = pairs[i:i + bs]

            # Encode input words and extract their correct labels.
            y = torch.tensor([l for _, l in chunk], device=DEVICE)
            logits = model(encode([w for w, _ in chunk]))

            # Compute cross-entropy loss with label smoothing.
            loss = F.cross_entropy(logits, y, label_smoothing=ls)

            # Backpropagate the loss and update model parameters.
            opt.zero_grad()
            loss.backward()

            # Clip gradients to prevent excessively large updates.
            nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()

            # Update the learning rate after each mini-batch.
            sched.step()

            # Accumulate training loss and correct predictions.
            loss_sum += loss.item() * len(chunk)
            correct += (logits.argmax(1) == y).sum().item()
            n += len(chunk)

        # Log average loss and accuracy at regular intervals.
        if ep == 0 or (ep + 1) % max(1, epochs // 6) == 0:
            log(f"    epoch {ep + 1:3d}/{epochs}   "
                f"loss {loss_sum / n:.3f}   "
                f"train accuracy {correct / n:.1%}")



@torch.no_grad()
def predict(model, encode, words):
    """Returns (0/1 predictions, P(pasta)) from the softmax output."""
    model.eval()
    p = F.softmax(model(encode(words)), dim=-1)[:, PASTA]
    return (p > 0.5).long().cpu().numpy(), p.cpu().numpy()
